require('dotenv').config();

const fs = require('fs');
const path = require('path');
const axios = require('axios');
const { Pool } = require('pg');
const express = require('express');
const cors = require('cors');

const app = express();
const port = Number(process.env.PORT || 3001);
const catalogPath = path.resolve(__dirname, '..', 'data', 'catalog.json');
const jsonBinBaseUrl = 'https://api.jsonbin.io/v3/b';
const jikanBaseUrl = 'https://api.jikan.moe/v4';
const supabaseCatalogTable = process.env.SUPABASE_CATALOG_TABLE || 'catalog';
const databaseUrl = process.env.DATABASE_URL;
const postgresPool = databaseUrl ? new Pool({ connectionString: databaseUrl, ssl: { rejectUnauthorized: false } }) : null;
let postgresSchemaPromise;

app.use(express.json({ limit: '2mb' }));
const allowedFrontendOrigin = process.env.FRONTEND_URL;
app.use(cors({ origin: (origin, callback) => {
  if (!origin || /^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(origin) || origin === allowedFrontendOrigin) return callback(null, true);
  return callback(new Error('Origem não autorizada pelo CORS.'));
} }));

function jsonBinConfiguration() {
  const masterKey = process.env.JSONBIN_MASTER_KEY;
  const binId = process.env.JSONBIN_BIN_ID;

  if (Boolean(masterKey) !== Boolean(binId)) {
    throw new Error('Configure JSONBIN_MASTER_KEY e JSONBIN_BIN_ID juntos, ou remova ambos para usar o catálogo local.');
  }

  return masterKey && binId ? { masterKey, binId } : null;
}

function supabaseConfiguration() {
  const url = process.env.SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (Boolean(url) !== Boolean(serviceRoleKey)) {
    throw new Error('Configure SUPABASE_URL e SUPABASE_SERVICE_ROLE_KEY juntos, ou remova ambos.');
  }
  return url && serviceRoleKey ? { url: url.replace(/\/$/, ''), serviceRoleKey } : null;
}

async function ensurePostgresSchema() {
  if (!postgresPool) return;
  if (!postgresSchemaPromise) {
    postgresSchemaPromise = postgresPool.query(`
      CREATE TABLE IF NOT EXISTS animes (
        id BIGINT PRIMARY KEY,
        slug TEXT NOT NULL UNIQUE,
        title TEXT NOT NULL,
        visibility TEXT NOT NULL DEFAULT 'draft',
        data JSONB NOT NULL
      );
      CREATE TABLE IF NOT EXISTS episodes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        anime_id BIGINT NOT NULL REFERENCES animes(id) ON DELETE CASCADE,
        episode_number NUMERIC,
        title TEXT,
        data JSONB NOT NULL
      );
      CREATE INDEX IF NOT EXISTS episodes_anime_id_idx ON episodes(anime_id);
    `).catch((error) => {
      postgresSchemaPromise = null;
      throw error;
    });
  }
  await postgresSchemaPromise;
}

async function readPostgresCatalog() {
  await ensurePostgresSchema();
  const result = await postgresPool.query(`
    SELECT a.data, COALESCE(json_agg(e.data ORDER BY e.episode_number NULLS LAST, e.id) FILTER (WHERE e.id IS NOT NULL), '[]') AS episodes
    FROM animes a
    LEFT JOIN episodes e ON e.anime_id = a.id
    GROUP BY a.id
    ORDER BY a.id
  `);
  return result.rows.map(({ data, episodes }) => ({ ...data, episodes }));
}

async function writePostgresCatalog(animes) {
  await ensurePostgresSchema();
  const client = await postgresPool.connect();
  try {
    await client.query('BEGIN');
    for (const anime of animes) {
      const { episodes = [], ...animeData } = anime;
      await client.query(`
        INSERT INTO animes (id, slug, title, visibility, data)
        VALUES ($1, $2, $3, $4, $5::jsonb)
        ON CONFLICT (id) DO UPDATE SET slug = EXCLUDED.slug, title = EXCLUDED.title, visibility = EXCLUDED.visibility, data = EXCLUDED.data
      `, [anime.id, anime.slug, anime.title, anime.visibility || 'draft', JSON.stringify(animeData)]);
      await client.query('DELETE FROM episodes WHERE anime_id = $1', [anime.id]);
      for (const episode of episodes) {
        await client.query(`INSERT INTO episodes (anime_id, episode_number, title, data) VALUES ($1, $2, $3, $4::jsonb)`, [anime.id, episode.number ?? episode.episode ?? null, episode.title || null, JSON.stringify(episode)]);
      }
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

function validateCatalog(animes) {
  if (!Array.isArray(animes)) {
    throw new Error('O campo "animes" precisa ser uma lista.');
  }

  const ids = new Set();
  const slugs = new Set();
  for (const anime of animes) {
    if (!anime || !anime.title || !anime.slug || !Array.isArray(anime.episodes)) {
      throw new Error('Cada anime precisa ter título, slug e uma lista de episódios.');
    }
    if (ids.has(String(anime.id)) || slugs.has(anime.slug)) {
      throw new Error('O catálogo não pode conter IDs ou slugs duplicados.');
    }
    ids.add(String(anime.id));
    slugs.add(anime.slug);
  }
}

function readLocalCatalog() {
  return JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
}

function writeLocalCatalog(animes) {
  const temporaryPath = `${catalogPath}.${process.pid}.tmp`;
  fs.writeFileSync(temporaryPath, `${JSON.stringify({ animes }, null, 2)}\n`, 'utf8');
  fs.renameSync(temporaryPath, catalogPath);
}

app.get('/api/animes', async (req, res) => {
  try {
    if (postgresPool) {
      return res.json({ animes: await readPostgresCatalog(), storage: 'postgres' });
    }
    const supabase = supabaseConfiguration();
    if (supabase) {
      const response = await axios.get(`${supabase.url}/rest/v1/${supabaseCatalogTable}`, {
        params: { select: 'animes', id: 'eq.1', limit: 1 },
        headers: { apikey: supabase.serviceRoleKey, Authorization: `Bearer ${supabase.serviceRoleKey}` },
      });
      const record = response.data[0];
      if (!record || !Array.isArray(record.animes)) throw new Error('A tabela do Supabase não contém um catálogo válido.');
      return res.json({ animes: record.animes, storage: 'supabase' });
    }
    const config = jsonBinConfiguration();
    if (!config) {
      const localCatalog = readLocalCatalog();
      return res.json({ animes: localCatalog.animes, storage: 'local' });
    }

    const response = await axios.get(
      `${jsonBinBaseUrl}/${encodeURIComponent(config.binId)}/latest`,
      { headers: { 'X-Master-Key': config.masterKey, 'X-Bin-Meta': 'false' } }
    );
    const record = response.data.record || response.data;
    if (!Array.isArray(record.animes)) {
      throw new Error('O Bin do Jsonbin não contém o campo "animes" como lista.');
    }
    res.json({ animes: record.animes, storage: 'jsonbin' });
  } catch (error) {
    console.error('Falha ao carregar o catálogo:', error.message);
    res.status(502).json({ error: error.message || 'Não foi possível carregar o catálogo.' });
  }
});

app.put('/api/animes', async (req, res) => {
  try {
    const { animes } = req.body;
    validateCatalog(animes);
    if (postgresPool) {
      await writePostgresCatalog(animes);
      return res.json({ animes, storage: 'postgres' });
    }
    const supabase = supabaseConfiguration();
    if (supabase) {
      await axios.post(`${supabase.url}/rest/v1/${supabaseCatalogTable}`, { id: 1, animes }, {
        params: { on_conflict: 'id' },
        headers: {
          apikey: supabase.serviceRoleKey,
          Authorization: `Bearer ${supabase.serviceRoleKey}`,
          'Content-Type': 'application/json',
          Prefer: 'resolution=merge-duplicates,return=minimal',
        },
      });
      return res.json({ animes, storage: 'supabase' });
    }
    const config = jsonBinConfiguration();

    if (!config) {
      writeLocalCatalog(animes);
      return res.json({ animes, storage: 'local' });
    }

    const response = await axios.put(
      `${jsonBinBaseUrl}/${encodeURIComponent(config.binId)}`,
      { animes },
      {
        headers: {
          'X-Master-Key': config.masterKey,
          'Content-Type': 'application/json',
        },
      }
    );
    res.json({ animes, storage: 'jsonbin', metadata: response.data.metadata });
  } catch (error) {
    console.error('Falha ao salvar o catálogo:', error.message);
    res.status(502).json({ error: error.message || 'Não foi possível salvar o catálogo.' });
  }
});

app.get('/api/mal/anime/:id', async (req, res) => {
  const malId = Number(req.params.id);
  if (!Number.isInteger(malId) || malId < 1) {
    return res.status(400).json({ error: 'Informe um ID válido do MyAnimeList.' });
  }
  try {
    const [animeResponse, staffResponse] = await Promise.all([
      axios.get(`${jikanBaseUrl}/anime/${malId}/full`, { timeout: 15000 }),
      axios.get(`${jikanBaseUrl}/anime/${malId}/staff`, { timeout: 15000 }),
    ]);
    const anime = animeResponse.data.data;
    const director = staffResponse.data.data?.find((item) => item.positions?.some((position) => /director/i.test(position)));
    res.json({ ...anime, director: director?.person?.name || '' });
  } catch (error) {
    const status = error.response?.status === 404 ? 404 : 502;
    res.status(status).json({ error: status === 404 ? 'Anime não encontrado no MyAnimeList.' : 'Não foi possível consultar o MyAnimeList agora.' });
  }
});

app.listen(port, '127.0.0.1', () => {
  console.log(`API do catálogo disponível em http://127.0.0.1:${port}`);
});
