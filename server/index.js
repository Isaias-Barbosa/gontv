function jsonBinConfiguration() {
  const masterKey = process.env.JSONBIN_MASTER_KEY;
  const binId = process.env.JSONBIN_BIN_ID;

  if (Boolean(masterKey) !== Boolean(binId)) {
    throw new Error('Configure JSONBIN_MASTER_KEY e JSONBIN_BIN_ID juntos, ou remova ambos para usar o catálogo local.');
  }

  return masterKey && binId ? { masterKey, binId } : null;
}

function supabaseConfiguration() {
  const url = process.env.SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (Boolean(url) !== Boolean(serviceRoleKey)) {
    throw new Error('Configure SUPABASE_URL e SUPABASE_SERVICE_ROLE_KEY juntos, ou remova ambos.');
  }
  return url && serviceRoleKey ? { url: url.replace(/\/$/, ''), serviceRoleKey } : null;
}

async function ensurePostgresSchema() {
  if (!postgresPool) return;
  if (!postgresSchemaPromise) {
    postgresSchemaPromise = postgresPool.query(`
      CREATE TABLE IF NOT EXISTS animes (
        id BIGINT PRIMARY KEY,
        slug TEXT NOT NULL UNIQUE,
        title TEXT NOT NULL,
        visibility TEXT NOT NULL DEFAULT 'draft',
        data JSONB NOT NULL
      );
      CREATE TABLE IF NOT EXISTS episodes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        anime_id BIGINT NOT NULL REFERENCES animes(id) ON DELETE CASCADE,
        episode_number NUMERIC,
        title TEXT,
        data JSONB NOT NULL
      );
      CREATE INDEX IF NOT EXISTS episodes_anime_id_idx ON episodes(anime_id);
      ALTER TABLE animes ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ;
      ALTER TABLE animes ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;
    `).catch((error) => {
      postgresSchemaPromise = null;
      throw error;
    });
  }
  await postgresSchemaPromise;
}

async function readPostgresCatalog(publicOnly = false) {
  await ensurePostgresSchema();
  const result = await postgresPool.query(`
    SELECT a.data, a.created_at, a.updated_at, COALESCE(json_agg(e.data ORDER BY e.episode_number NULLS LAST, e.id) FILTER (WHERE e.id IS NOT NULL), '[]') AS episodes
    FROM animes a
    LEFT JOIN episodes e ON e.anime_id = a.id
    WHERE ($1::boolean = FALSE OR a.visibility <> 'draft')
    GROUP BY a.id
    ORDER BY a.id
  `, [publicOnly]);
  return result.rows.map(({ data, episodes, created_at, updated_at }) => ({ ...data, episodes, createdAt: created_at, updatedAt: updated_at }));
}

async function writePostgresCatalog(animes) {
  await ensurePostgresSchema();
  const client = await postgresPool.connect();
  try {
    await client.query('BEGIN');
    for (const anime of animes) {
      const { episodes = [], ...animeData } = anime;
      await client.query(`
        INSERT INTO animes (id, slug, title, visibility, data, created_at, updated_at)
        VALUES ($1, $2, $3, $4, $5::jsonb, NOW(), NOW())
        ON CONFLICT (id) DO UPDATE SET slug = EXCLUDED.slug, title = EXCLUDED.title, visibility = EXCLUDED.visibility, data = EXCLUDED.data, updated_at = NOW()
      `, [anime.id, anime.slug, anime.title, anime.visibility || 'draft', JSON.stringify(animeData)]);
      await client.query('DELETE FROM episodes WHERE anime_id = $1', [anime.id]);
      for (const episode of episodes) {
        await client.query(`INSERT INTO episodes (anime_id, episode_number, title, data) VALUES ($1, $2, $3, $4::jsonb)`, [anime.id, episode.number ?? episode.episode ?? null, episode.title || null, JSON.stringify(episode)]);
      }
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

function validateCatalog(animes) {
  if (!Array.isArray(animes)) {
    throw new Error('O campo "animes" precisa ser uma lista.');
  }

  const ids = new Set();
  const slugs = new Set();
  for (const anime of animes) {
    if (!anime || !anime.title || !anime.slug || !Array.isArray(anime.episodes)) {
      throw new Error('Cada anime precisa ter título, slug e uma lista de episódios.');
    }
    if (ids.has(String(anime.id)) || slugs.has(anime.slug)) {
      throw new Error('O catálogo não pode conter IDs ou slugs duplicados.');
    }
    ids.add(String(anime.id));
    slugs.add(anime.slug);
  }
}

function readLocalCatalog() {
  return JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
}

function writeLocalCatalog(animes) {
  const temporaryPath = `${catalogPath}.${process.pid}.tmp`;
  fs.writeFileSync(temporaryPath, `${JSON.stringify({ animes }, null, 2)}\n`, 'utf8');
  fs.renameSync(temporaryPath, catalogPath);
}

async function loadCatalog(publicOnly = false) {
  const visible = animes => publicOnly ? animes.filter(anime => anime.visibility !== 'draft') : animes;
  if (postgresPool) return { animes: await readPostgresCatalog(publicOnly), storage: 'postgres' };
  const supabase = supabaseConfiguration();
  if (supabase) {
    const response = await axios.get(`${supabase.url}/rest/v1/${supabaseCatalogTable}`, {
      params: { select: 'animes', id: 'eq.1', limit: 1 },
      headers: { apikey: supabase.serviceRoleKey, Authorization: `Bearer ${supabase.serviceRoleKey}` },
    });
    if (!Array.isArray(response.data[0]?.animes)) throw new Error('O Supabase não contém um catálogo válido.');
    return { animes: visible(response.data[0].animes), storage: 'supabase' };
  }
  const config = jsonBinConfiguration();
  if (!config) return { animes: visible(readLocalCatalog().animes), storage: 'local' };
  const response = await axios.get(`${jsonBinBaseUrl}/${encodeURIComponent(config.binId)}/latest`,
    { headers: { 'X-Master-Key': config.masterKey, 'X-Bin-Meta': 'false' } });
  const record = response.data.record || response.data;
  if (!Array.isArray(record.animes)) throw new Error('O Jsonbin não contém um catálogo válido.');
  return { animes: visible(record.animes), storage: 'jsonbin' };
}
const publicCatalogCache = createCatalogCache(() => loadCatalog(true));
