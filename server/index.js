app.get('/api/animes/public', async (req, res, next) => {
  try {
    res.set('Cache-Control', 'public, max-age=0, must-revalidate');
    res.json(await publicCatalogCache.get());
  } catch (error) { next(error); }
});
app.get('/api/animes', auth.optionalUser, async (req, res, next) => {
  try {
    res.set('Cache-Control', 'no-store');
    res.json(await loadCatalog(!req.user));
  } catch (error) { next(error); }
});

app.post('/api/animes/changes', auth.optionalUser, auth.requireUser, async (req, res, next) => {
  try {
    if (!postgresPool) return res.status(503).json({ error: 'Esta operação requer PostgreSQL.' });
    await ensurePostgresSchema();
    await applyCatalogChanges(postgresPool, req.body.changes);
    publicCatalogCache.clear();
    res.json({ animes: await readPostgresCatalog(), storage: 'postgres' });
  } catch (error) {
    if (error.code === '23505') return res.status(409).json({ error: 'Já existe um anime com esse ID ou slug. Atualize o catálogo e tente novamente.' });
    next(error);
  }
});

app.put('/api/animes', auth.optionalUser, auth.requireUser, async (req, res) => {
  try {
    const { animes } = req.body;
    validateCatalog(animes);
    if (postgresPool) {
      await writePostgresCatalog(animes);
      publicCatalogCache.clear();
      return res.json({ animes: await readPostgresCatalog(), storage: 'postgres' });
    }
    const supabase = supabaseConfiguration();
    if (supabase) {
      await axios.post(`${supabase.url}/rest/v1/${supabaseCatalogTable}`, { id: 1, animes }, {
        params: { on_conflict: 'id' },
        headers: {
          apikey: supabase.serviceRoleKey,
          Authorization: `Bearer ${supabase.serviceRoleKey}`,
          'Content-Type': 'application/json',
          Prefer: 'resolution=merge-duplicates,return=minimal',
        },
      });
      publicCatalogCache.clear();
      return res.json({ animes, storage: 'supabase' });
    }
    const config = jsonBinConfiguration();

    if (!config) {
      writeLocalCatalog(animes);
      publicCatalogCache.clear();
      return res.json({ animes, storage: 'local' });
    }

    const response = await axios.put(
      `${jsonBinBaseUrl}/${encodeURIComponent(config.binId)}`,
      { animes },
      {
        headers: {
          'X-Master-Key': config.masterKey,
          'Content-Type': 'application/json',
        },
      }
    );
    publicCatalogCache.clear();
    res.json({ animes, storage: 'jsonbin', metadata: response.data.metadata });
  } catch (error) {
    console.error('Falha ao salvar o catálogo:', error.message);
    res.status(502).json({ error: error.message || 'Não foi possível salvar o catálogo.' });
  }
});

app.use('/api/mal', auth.optionalUser, auth.requireUser, createMalRouter());
app.use('/api/anilist', auth.optionalUser, auth.requireUser, createAniListRouter());

app.get('/api/admin/dashboard', auth.optionalUser, auth.requireUser, async (req, res, next) => {
  try {
    const animes = await readPostgresCatalog();
    const users = await postgresPool.query('SELECT COUNT(*)::int AS total FROM users');
    const recentAnimes = [...animes].sort((a, b) =>
      (new Date(b.createdAt || 0) - new Date(a.createdAt || 0)) || Number(b.id) - Number(a.id)
    ).slice(0, 8);
    res.json({
      totalAnimes: animes.length,
      published: animes.filter(anime => anime.visibility !== 'draft').length,
      drafts: animes.filter(anime => anime.visibility === 'draft').length,
      episodes: animes.reduce((total, anime) => total + anime.episodes.length, 0),
      users: users.rows[0].total, recentAnimes,
    });
  } catch (error) { next(error); }
});

app.use((error, req, res, next) => {
  if (res.headersSent) return next(error);
  console.error('Falha na API:', error.message);
  res.status(error.status || 500).json({ error: error.status ? error.message : 'Não foi possível concluir a operação.' });
});

async function start() {
  if (process.env.ADMIN_PASSWORD) {
    await bootstrapAdmin(postgresPool, auth, {name:process.env.ADMIN_NAME, email:process.env.ADMIN_EMAIL, password:process.env.ADMIN_PASSWORD});
  }
  app.listen(port, host, () => console.log(`API do catálogo disponível em http://${host}:${port}`));
}
if (require.main === module) start().catch(error => { console.error('Falha ao iniciar a API:', error.message); process.exitCode = 1; });
module.exports = { app, postgresPool };
