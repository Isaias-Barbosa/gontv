const crypto = require('crypto');
const bcrypt = require('bcryptjs');
const express = require('express');

const publicColumns = 'id, name, email, role, active, created_at AS "createdAt"';
const tokenHash = token => crypto.createHash('sha256').update(token).digest('hex');
const validPassword = password => typeof password === 'string' && password.length >= 12 && Buffer.byteLength(password, 'utf8') <= 72;
const validEmail = email => typeof email === 'string' && email.length <= 254 && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
const fail = (status, message) => Object.assign(new Error(message), { status });
const asyncRoute = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);

function createAuth(pool) {
  let schemaPromise;
  const ensureSchema = () => {
    if (!pool) return Promise.reject(fail(503, 'Configure o PostgreSQL para acessar o painel.'));
    if (!schemaPromise) schemaPromise = pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
        role TEXT NOT NULL CHECK (role IN ('admin', 'editor')),
        active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS admin_sessions (
        token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL
      );
      CREATE INDEX IF NOT EXISTS admin_sessions_user_idx ON admin_sessions(user_id);
      CREATE TABLE IF NOT EXISTS auth_attempts (
        key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires_at TIMESTAMPTZ NOT NULL
      );
    `).catch(error => { schemaPromise = null; throw error; });
    return schemaPromise;
  };
  const optionalUser = asyncRoute(async (req, res, next) => {
    const match = /^Bearer ([a-f0-9]{64})$/.exec(req.get('Authorization') || '');
    if (match) {
      await ensureSchema();
      const result = await pool.query(`SELECT u.id, u.name, u.email, u.role, u.active
        FROM admin_sessions s JOIN users u ON u.id = s.user_id
        WHERE s.token_hash = $1 AND s.expires_at > NOW() AND u.active = TRUE`, [tokenHash(match[1])]);
      req.user = result.rows[0];
      req.sessionHash = tokenHash(match[1]);
    }
    next();
  });
  const requireUser = (req, res, next) => req.user ? next() : res.status(401).json({ error: 'Sua sessão expirou. Entre novamente.' });
  const requireAdmin = (req, res, next) => req.user?.role === 'admin' ? next() : res.status(403).json({ error: 'Apenas administradores podem gerenciar usuários.' });
  const router = express.Router();
  router.use((req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
  router.post('/auth/login', asyncRoute(async (req, res) => {
    await ensureSchema();
    const email = String(req.body.email || '').trim().toLowerCase();
    const password = req.body.password;
    if (!validEmail(email) || !validPassword(password)) throw fail(401, 'E-mail ou senha inválidos.');
    const key = tokenHash(email);
    const attempt = await pool.query(`INSERT INTO auth_attempts (key, attempts, expires_at) VALUES ($1, 1, NOW() + INTERVAL '15 minutes')
      ON CONFLICT (key) DO UPDATE SET attempts = CASE WHEN auth_attempts.expires_at <= NOW() THEN 1 ELSE auth_attempts.attempts + 1 END,
      expires_at = CASE WHEN auth_attempts.expires_at <= NOW() THEN NOW() + INTERVAL '15 minutes' ELSE auth_attempts.expires_at END RETURNING attempts`, [key]);
    if (attempt.rows[0].attempts > 10) { res.set('Retry-After', '900'); throw fail(429, 'Muitas tentativas. Aguarde 15 minutos e tente novamente.'); }
    const result = await pool.query(`SELECT ${publicColumns}, password_hash FROM users WHERE email = $1`, [email]);
    const user = result.rows[0];
    // Compare even for unknown accounts to avoid a fast account-existence response.
    const hash = user?.password_hash || '$2a$12$R9h/cIPz0gi.URNNX3kh2OPST9/PgBkqquzi.Ss7KIUgO2t0jWMUW';
    const matches = await bcrypt.compare(password, hash);
    if (!user || !user.active || !matches) throw fail(401, 'E-mail ou senha inválidos.');
    const token = crypto.randomBytes(32).toString('hex');
    await pool.query(`DELETE FROM auth_attempts WHERE key = $1 OR expires_at < NOW()`, [key]);
    await pool.query('DELETE FROM admin_sessions WHERE expires_at <= NOW()');
    await pool.query(`INSERT INTO admin_sessions (token_hash, user_id, expires_at) VALUES ($1, $2, NOW() + INTERVAL '12 hours')`, [tokenHash(token), user.id]);
    delete user.password_hash;
    res.json({ token, user });
  }));
  router.get('/auth/me', optionalUser, requireUser, (req, res) => res.json({ user: req.user }));
  router.post('/auth/logout', optionalUser, requireUser, asyncRoute(async (req, res) => {
    await pool.query('DELETE FROM admin_sessions WHERE token_hash = $1', [req.sessionHash]);
    res.sendStatus(204);
  }));
  router.use('/admin', optionalUser, requireUser);
  router.get('/admin/users', requireAdmin, asyncRoute(async (req, res) => {
    const result = await pool.query(`SELECT ${publicColumns} FROM users ORDER BY created_at DESC, id DESC`);
    res.json({ users: result.rows });
  }));
  router.post('/admin/users', requireAdmin, asyncRoute(async (req, res) => {
    const name = String(req.body.name || '').trim();
    const email = String(req.body.email || '').trim().toLowerCase();
    const { password, role } = req.body;
    if (!name || name.length > 100 || !validEmail(email) || !validPassword(password) || !['admin','editor'].includes(role)) throw fail(400, 'Preencha nome, e-mail, perfil e senha de 12 caracteres ou mais (máximo 72 bytes).');
    const hash = await bcrypt.hash(password, 12);
    const result = await pool.query(`INSERT INTO users (name, email, password_hash, role) VALUES ($1, $2, $3, $4) RETURNING ${publicColumns}`, [name,email,hash,role]);
    res.status(201).json({ user: result.rows[0] });
  }));
  router.patch('/admin/users/:id', requireAdmin, asyncRoute(async (req, res) => {
    if (!/^\d+$/.test(req.params.id)) throw fail(400, 'Usuário inválido.');
    const { role, active, password } = req.body;
    if (!['admin','editor'].includes(role) || typeof active !== 'boolean' || (password && !validPassword(password))) throw fail(400, 'Confira o perfil, o estado e a senha (mínimo de 12 caracteres).');
    if (String(req.user.id) === req.params.id && (!active || role !== 'admin')) throw fail(400, 'Você não pode desativar ou remover seu próprio acesso de administrador.');
    const hash = password ? await bcrypt.hash(password,12) : null;
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query('LOCK TABLE users IN SHARE ROW EXCLUSIVE MODE');
      const result = await client.query(`UPDATE users SET role = $1, active = $2, password_hash = COALESCE($3, password_hash) WHERE id = $4 RETURNING ${publicColumns}`, [role,active,hash,req.params.id]);
      if (!result.rows.length) throw fail(404, 'Usuário não encontrado.');
      const remaining = await client.query("SELECT 1 FROM users WHERE role = 'admin' AND active = TRUE LIMIT 1");
      if (!remaining.rowCount) throw fail(400, 'Mantenha pelo menos um administrador ativo.');
      if (password || !active) await client.query('DELETE FROM admin_sessions WHERE user_id = $1', [req.params.id]);
      await client.query('COMMIT');
      res.json({ user: result.rows[0] });
    } catch (error) { await client.query('ROLLBACK'); throw error; }
    finally { client.release(); }
  }));
  router.use((error, req, res, next) => {
    if (res.headersSent) return next(error);
    if (error.code === '23505') return res.status(409).json({error:'Este e-mail já está cadastrado.'});
    if (!error.status) console.error('Falha na autenticação:', error.message);
    res.status(error.status || 500).json({ error: error.status ? error.message : 'Não foi possível concluir a operação. Tente novamente.' });
  });
  return { router, optionalUser, requireUser, requireAdmin, ensureSchema };
}

async function bootstrapAdmin(pool, auth, {name,email,password}) {
  if (!validEmail(email) || !validPassword(password)) throw new Error('Defina ADMIN_EMAIL e ADMIN_PASSWORD (12 caracteres ou mais, máximo 72 bytes).');
  await auth.ensureSchema();
  const hash = await bcrypt.hash(password,12);
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('LOCK TABLE users IN SHARE ROW EXCLUSIVE MODE');
    const exists = await client.query("SELECT 1 FROM users WHERE role = 'admin' AND active = TRUE LIMIT 1");
    if (exists.rowCount) { await client.query('ROLLBACK'); return false; }
    await client.query("INSERT INTO users (name,email,password_hash,role) VALUES ($1,$2,$3,'admin')", [name || 'Administrador',email.trim().toLowerCase(),hash]);
    await client.query('COMMIT');
    return true;
  } catch(error) { await client.query('ROLLBACK'); throw error; }
  finally { client.release(); }
}
module.exports = { createAuth, bootstrapAdmin, validPassword, validEmail };
