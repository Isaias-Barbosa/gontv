require('dotenv').config();
const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

async function main() {
  if (!process.env.DATABASE_URL) throw new Error('Defina DATABASE_URL no .env antes de migrar.');
  const catalog = JSON.parse(fs.readFileSync(path.resolve(__dirname, '..', 'data', 'catalog.json'), 'utf8'));
  const client = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
  await client.connect();
  try {
    await client.query(`
      CREATE TABLE IF NOT EXISTS animes (id BIGINT PRIMARY KEY, slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL, visibility TEXT NOT NULL DEFAULT 'draft', data JSONB NOT NULL);
      CREATE TABLE IF NOT EXISTS episodes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, anime_id BIGINT NOT NULL REFERENCES animes(id) ON DELETE CASCADE, episode_number NUMERIC, title TEXT, data JSONB NOT NULL);
      CREATE INDEX IF NOT EXISTS episodes_anime_id_idx ON episodes(anime_id);
    `);
    await client.query('BEGIN');
    for (const anime of catalog.animes) {
      const { episodes = [], ...animeData } = anime;
      await client.query(`INSERT INTO animes (id, slug, title, visibility, data) VALUES ($1, $2, $3, $4, $5::jsonb) ON CONFLICT (id) DO UPDATE SET slug = EXCLUDED.slug, title = EXCLUDED.title, visibility = EXCLUDED.visibility, data = EXCLUDED.data`, [anime.id, anime.slug, anime.title, anime.visibility || 'draft', JSON.stringify(animeData)]);
      await client.query('DELETE FROM episodes WHERE anime_id = $1', [anime.id]);
      for (const episode of episodes) await client.query('INSERT INTO episodes (anime_id, episode_number, title, data) VALUES ($1, $2, $3, $4::jsonb)', [anime.id, episode.number ?? episode.episode ?? null, episode.title || null, JSON.stringify(episode)]);
    }
    await client.query('COMMIT');
    console.log(`Migrados ${catalog.animes.length} animes para o PostgreSQL.`);
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    await client.end();
  }
}

main().catch((error) => { console.error('Falha na migração:', error.message); process.exitCode = 1; });
